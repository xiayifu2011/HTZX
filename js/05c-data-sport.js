    /* ==================================================================
     * 抽一条运动事件
     * ------------------------------------------------------------------
     * 只从 SPORT_EVENTS 里挑，挑不到就返回 null（调用方直接跳过）。
     * ================================================================== */

    function pickSportEvent() {
      if (!Array.isArray(SPORT_EVENTS) || !SPORT_EVENTS.length) return null;
      const pool = SPORT_EVENTS.filter(e =>
        e && e.id && !(S.evCntWeek && S.evCntWeek[e.id])
        && (!e.cond || e.cond(S))
        && (typeof eventAllowed === "function" ? eventAllowed(e) : true)
      );
      if (!pool.length) return null;
      const effW = e => Math.max(0.1, (typeof eventWeight === "function") ? eventWeight(e) : num(e.w, 1));
      const total = pool.reduce((s, e) => s + effW(e), 0);
      let r = Math.random() * total, ev = pool[0];
      for (const e of pool) {r -= effW(e); if (r <= 0) {ev = e; break;} }
      return ev;
    }
