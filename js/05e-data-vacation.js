    /* ==================================================================
     * 假期流程
     * ------------------------------------------------------------------
     * 学期第 20 周结束后进来，跑完所有主事件（含连锁）再回学期。
     * 假期不占周数 —— S.week 在假期里不变，顶栏也不再显示「第 N 周」。
     * ================================================================== */

    /* 这个学期读完之后的假期是哪一套 */
    function vacationSetOf(term) {
      /* term 0 → 初一寒假(0)，term 1 → 初一暑假(1)，term 2 → 初二寒假(2)……
       * term 5（初三下）读完直接中考，没有假期，兜底返回 null。 */
      const i = clampNum(term, 0, 9, 0);
      return VACATION_SETS[i] || null;
    }

    /* 现在是不是在假期里 */
    function inVacation() {
      return !!(S && S.vac && S.vac.on);
    }

    /* 进入假期 */
    function startVacation() {
      const set = vacationSetOf(S.term);
      /* 没有对应的假期（比如初三下读完了）→ 直接进下一学期 */
      if (!set) {endVacation(); return;}

      S.vac = {
        on: true,
        id: set.id,
        kind: set.kind,
        name: set.name,
        /* 主事件队列：随机打乱，每次玩的顺序不一样 */
        queue: (set.mains || []).slice().sort(() => Math.random() - 0.5),
        done: 0
      };
      if (typeof setBackground === "function") setBackground("alt");
      say(`🎒 ${set.name} —— ${set.kind === "winter" ? "寒假" : "暑假"}开始了`, "week-head");
      say(set.intro, "sys");
      if (typeof renderHUD === "function") renderHUD();
      /* v1.3：假期开头先问一句要不要出去旅游。
       * 钱够才会问；选了就先跑景点，逛完再回来跑常规假期事件。 */
      if (typeof offerTravel === "function") {
        setTimeout(() => offerTravel(() => nextVacationEvent()), 0);
      } else {
        nextVacationEvent();
      }
    }

    /* 弹下一条假期事件 */
    function nextVacationEvent() {
      if (!S || !inVacation()) return;
      if (!S.vac.queue.length) {endVacation(); return;}
      const id = S.vac.queue.shift();
      S.vac.done++;
      const ev = VACATION_EVENTS[id];
      if (!ev) {nextVacationEvent(); return;}

      const opts = (ev.opts || []).filter(o => {
        if (typeof o.cond === "function") {try {return !!o.cond(S);} catch (e) {return false;}}
        return true;
      });
      showPopup({
        kind: "fixed",
        title: ev.t,
        badge: S.vac.kind === "winter" ? "❄️ 寒假" : "🌞 暑假",
        body: ev.c,
        options: (opts.length ? opts : [{t: "继续", run: () => { }}]).map(o => ({
          t: o.t,
          fn: () => {
            if (typeof execOption === "function") execOption(o);
            else if (typeof o.run === "function") o.run(S);
            // 连锁：本条选项指定了 next 就接着弹，否则取下一条主事件
            if (o.next && VACATION_EVENTS[o.next]) {
              S.vac.queue.unshift(o.next);
            }
          }
        }))
      }, () => {
        renderHUD();
        nextVacationEvent();
      });
    }

    /* 假期结束 → 回学期，周数继续往上数 */
    function endVacation() {
      if (!S) return;
      S.vac = null;
      if (typeof setBackground === "function") setBackground("main");
      say(`🎒 ${S.vacNameShown || "假期"}结束了，新的学期开始了。`, "week-head");
      S.term++;
      nextWeek();
    }
