    const SUBJ_TALENT = {数学: "数学脑", 语文: "语感天成", 英语: "单词机器", 物理: "实验狂人", 化学: "实验狂人", 历史: "史海钩沉", 生物: "史海钩沉"};

    /* ==================================================================
     * v1.3 卷面满分与中考折算
     * ------------------------------------------------------------------
     * ① 平时卷面满分（SUBJ_FULL）
     *    生物 / 物理 / 化学 = 90 —— 这三科另有 10 分的实验操作考试
     *    （实验分在「实验操作考试」事件里拿，见 js/08-data-events-school.js）
     *    其余科目 = 100
     *
     * ② 中考折算权重（ZK_WEIGHT）
     *    语数英 100%，物 50%，史政 40%，生 40%，地 30%，化 30%
     *    折算后总分满分 = 100+100+100+50+40+40+40+30+30 = 530
     *
     * ③ 语文曲线（CHINESE_KNEE / CHINESE_SLOPE）
     *    初中语文极难上 90：87 以下照常好提，87 以上每 1 分要 2.5 倍学力。
     *    于是语文的实际上限约 92，95 基本是天花板。
     * ================================================================== */
    const SUBJ_FULL = {语文: 100, 数学: 100, 英语: 100, 物理: 90, 化学: 90, 生物: 90, 地理: 100, 历史: 100, 政治: 100};
    const ZK_WEIGHT = {语文: 1.0, 数学: 1.0, 英语: 1.0, 物理: 0.5, 化学: 0.3, 生物: 0.4, 地理: 0.3, 历史: 0.4, 政治: 0.4};
    const CHINESE_KNEE = 87, CHINESE_SLOPE = 2.5;

    /* 某科的卷面满分（中考实验分另算，不含在这里） */
    function fullMarkOf(sub) {return clampNum(SUBJ_FULL[sub], 0, 100, 100);}

    /* 生地会考考哪两科 —— 固定在初二结束时考，之后成绩锁死 */
    const HK_SUBJECTS = ["生物", "地理"];

    /* 有实验操作考试的科目（各 10 分） */
    const EXP_SUBJECTS = ["生物", "物理", "化学"];
    const EXP_SCORE = 10;

    /* 语文曲线：87 以下不动，以上每分要 2.5 倍学力
     * 传入的是「百分制原始分」，返回压缩后的实际卷面分。 */
    function chineseCurve(v) {
      const x = clampNum(v, 0, 100, 0);
      if (x <= CHINESE_KNEE) return x;
      return CHINESE_KNEE + (x - CHINESE_KNEE) / CHINESE_SLOPE;
    }

    /* 任意科目：百分制原始分 → 实际卷面分（含满分换算与语文曲线） */
    function toPaperScore(sub, raw100) {
      const r = clampNum(raw100, 0, 100, 0);
      let v = (sub === "语文") ? chineseCurve(r) : r;
      return clampNum(v * fullMarkOf(sub) / 100, 0, fullMarkOf(sub), 0);
    }

    /* 第几学期考哪几科。term 传成 undefined / NaN 也不会炸，一律退回初一 */
    function subjectsOf(term) {
      const t = clamp(Math.floor(clampNum(term, 0, 9, 0) / 2), 0, 2);
      return SUBJECTS_BY_GRADE[t] || SUBJECTS_BY_GRADE[0];
    }

